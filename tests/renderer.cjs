const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {parseHTML} = require('linkedom');
const {document, window} = parseHTML('<html><body></body></html>');
const context = vm.createContext({document, window, URL, setTimeout, clearTimeout});
vm.runInContext(fs.readFileSync('src/horizon-renderer.js', 'utf8'), context);
const render = text => context.FolioHorizon.render(text);
const profile = render('[center][heading][color=cyan]Name[/color]\n[big]Subtitle[/big][/heading][/center][hr][img=4645005]meanstoanend[/img]');
assert.equal(profile.querySelector('.centerText h2 .cyanText').textContent, 'Name');
assert.equal(profile.querySelector('.bigText').textContent, 'Subtitle');
assert.equal(profile.querySelectorAll('hr').length, 1);
assert.match(profile.querySelector('.placeholder-image').textContent, /4645005.*meanstoanend/);
assert.equal(render('A\n\n B').textContent, 'A\n\n B');
assert.equal(render('[noparse][b]literal[/b]\n[/noparse]').textContent, '[b]literal[/b]\n');
const scientific = render('H[sup]2[/sup]O and x[sub]n[/sub]');
assert.equal(scientific.querySelector('sup').textContent, '2');
assert.equal(scientific.querySelector('sub').textContent, 'n');
assert.equal(render('<script>alert(1)</script>').querySelector('script'), null);
assert.equal(render('[url=javascript:alert(1)]bad[/url]').querySelector('a'), null);
assert.equal(render('[url=https://example.com]Visit[/url]').querySelector('a').getAttribute('rel'), 'noopener noreferrer');
const collapse = render('[collapse=Details]Body[/collapse]');
assert.equal(collapse.querySelector('.bbcode-collapse-body').style.height, '0');
collapse.querySelector('.bbcode-collapse-header').click();
assert.equal(collapse.querySelector('.bbcode-collapse').classList.contains('collapsed'), false);
assert.equal(render('[icon]Test Name[/icon]').querySelector('img').getAttribute('src'), 'https://static.f-list.net/images/avatar/test%20name.png');
console.log('Horizon renderer DOM checks passed');
